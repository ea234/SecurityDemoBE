
CREATE TABLE demo_auth_users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    enable BOOLEAN NOT NULL,
    locked BOOLEAN NOT NULL,
    CONSTRAINT uk_demo_auth_users_username UNIQUE (username)
);

CREATE TABLE demo_auth_authorities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    authority VARCHAR(255),
    user_entity_id INTEGER NOT NULL,
    CONSTRAINT fk_demo_auth_authorities_user
        FOREIGN KEY (user_entity_id)
        REFERENCES demo_auth_users(id)
);

CREATE INDEX idx_demo_auth_authorities_user
    ON demo_auth_authorities(user_entity_id);

